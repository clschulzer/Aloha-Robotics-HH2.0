#!/usr/bin/env node
/* Runs every architecture once on the same synthetic hospital ("one shot each solution"),
   then the scenarios that could change the answer. Writes results/results.json and
   results/RESULTS.md. Usage: node Documentation/architecture-options/sim/run.cjs [runs]   (default 200 base, 100 per scenario) */
'use strict';
const fs = require('fs');
const path = require('path');
const S = require('./model.js');

const RUNS = Number(process.argv[2]) || 200;
const SCEN_RUNS = Math.max(20, Math.round(RUNS / 2));

const SCENARIOS = [
  { id: 'base', name: 'Base case (our assumptions)', set: {} },
  { id: 'wake', name: 'Siemens confirms the C-arm can be switched on remotely', set: { remoteWake: true } },
  { id: 'short', name: 'Install shrinks to 30 min (A/B slots, vendor side)', set: { installMin: 30 } },
  { id: 'lan', name: 'Every C-arm gets the package while in use (network in every OR)', set: { orLan: 1 } },
  { id: 'nosocket', name: 'No socket near any parking spot', set: { noSocket: 1 } },
  { id: 'thin', name: 'Thin evening and night staff', set: { acceptEve: 0.6, acceptLate: 0.3, acceptMove: 0.2 } },
  { id: 'big', name: 'Big site: 30 C-arms, up to 6 installs per night', set: { fleet: 30, maxPerNight: 6 } },
  { id: 'nextgen', name: 'Whole fleet is next gen and the hospital accepts the modem', set: { nextGen: 1, cellularAllowed: true } },
];

const pct = (x) => (Number.isFinite(x) ? Math.round(100 * x) + ' %' : 'n/a');
const num = (x, d = 1) => (Number.isFinite(x) ? x.toFixed(d) : 'n/a');
const eur = (x) => (x ? '€' + Math.round(x / 1000) + 'k' : '€0');
const days = (r) => (r.reached90Share >= 0.5 ? String(Math.round(r.daysTo90Median)) : 'not reached');

/* "Best buy": within 3 points of the best coverage, the lowest capex, then the fewest clinic minutes. */
function bestBuy(results) {
  const top = Math.max(...results.map((r) => r.patchedByDeadline));
  const near = results.filter((r) => r.patchedByDeadline >= top - 0.03);
  near.sort((a, b) => a.capexEUR - b.capexEUR || a.staffMinutes - b.staffMinutes || b.patchedByDeadline - a.patchedByDeadline);
  const most = results.slice().sort((a, b) => b.patchedByDeadline - a.patchedByDeadline || a.visits - b.visits)[0];
  return { most: most.id, buy: near[0].id, top };
}

const t0 = Date.now();
const out = { generated: new Date().toISOString(), runs: RUNS, scenarioRuns: SCEN_RUNS, scenarios: [] };
for (const sc of SCENARIOS) {
  const res = S.simulate(Object.assign({ runs: sc.id === 'base' ? RUNS : SCEN_RUNS }, sc.set));
  const pick = bestBuy(res.results);
  out.scenarios.push({ id: sc.id, name: sc.name, set: sc.set, params: res.params, best: pick, results: res.results });
  process.stdout.write(`${sc.id.padEnd(9)} most coverage ${pick.most}, best buy ${pick.buy}\n`);
}
out.ms = Date.now() - t0;

const dir = path.join(__dirname, 'results');
fs.mkdirSync(dir, { recursive: true });
fs.writeFileSync(path.join(dir, 'results.json'), JSON.stringify(out, null, 1) + '\n');
// A compact copy as a script, so Documentation/architecture-options/index.html can show the scenarios from file:// (no fetch needed).
const compact = { generated: out.generated, runs: out.runs, scenarioRuns: out.scenarioRuns, scenarios: out.scenarios.map((sc) => ({
  id: sc.id, name: sc.name, set: sc.set, best: sc.best,
  results: sc.results.map((r) => ({ id: r.id, key: r.key, short: r.short, name: r.name, patchedByDeadline: +r.patchedByDeadline.toFixed(4),
    daysTo90Median: Number.isFinite(r.daysTo90Median) ? r.daysTo90Median : null, reached90Share: r.reached90Share,
    staffPerPatched: Number.isFinite(r.staffPerPatched) ? +r.staffPerPatched.toFixed(2) : null, visits: +r.visits.toFixed(2),
    robotJobs: +r.robotJobs.toFixed(2), capexEUR: r.capexEUR })) })) };
fs.writeFileSync(path.join(dir, 'results.js'), '/* generated by Documentation/architecture-options/sim/run.cjs */\nwindow.BREIF_RESULTS = ' + JSON.stringify(compact) + ';\n');

const base = out.scenarios[0];
const P = base.params;
const L = [];
L.push('# Simulation results', '');
L.push(`Generated by \`node Documentation/architecture-options/sim/run.cjs\`: ${RUNS} runs for the base case, ${SCEN_RUNS} per scenario, seed ${P.seed}.`);
L.push('Synthetic hospital, synthetic people, one fleet-wide security patch. Every input is in `Documentation/architecture-options/sim/model.js` (`PARAMS`), and almost all of them are assumptions.');
L.push('Use this to see **which assumption decides which architecture wins**. These are not forecasts, and they don\'t belong on a pitch slide.', '');
L.push(`## Base case: ${P.fleet} C-arms, ${P.installMin}-minute install, deadline day ${P.deadline}, at most ${P.maxPerNight} installs per night`, '');
L.push('| Option | Patched by the deadline | Median days to 90 % | Clinic minutes per patched C-arm | Pulled mid-install per 100 starts | Dead on arrival per round | Escalations (dead on arrival + missed deadline) | Robot missions | Hardware (one site) |');
L.push('|---|---|---|---|---|---|---|---|---|');
for (const r of base.results) {
  L.push(`| **${r.id} ${r.name}** | ${pct(r.patchedByDeadline)} (${pct(r.patchedByDeadlineP10)} to ${pct(r.patchedByDeadlineP90)}) | ${days(r)} | ${num(r.staffPerPatched)} | ${num(r.pulledPer100)} | ${num(r.doa, 2)} | ${num(r.visits)} | ${num(r.robotJobs)} | ${eur(r.capexEUR)} |`);
}
L.push('', 'The range shows the 10th to 90th percentile across runs. A mean below its range means a few runs did much worse than most. "Escalations" means someone has to be sent on site or a manual plan is needed.', '');
L.push('### Why windows were lost (base case, per round)', '');
L.push('| Option | Top reasons |', '|---|---|');
for (const r of base.results) L.push(`| ${r.id} ${r.name} | ${r.topReasons.map((x) => `${x.why} (${num(x.perRun)})`).join(' · ') || 'none'} |`);
L.push('', '## What changes the answer', '');
L.push('Each cell shows the share of the fleet patched by the deadline. "Best buy" is the cheapest option within 3 points of the best coverage, with fewest clinic minutes as the tie-breaker.', '');
const ids = base.results.map((r) => r.id);
L.push('| Scenario | ' + ids.join(' | ') + ' | Most coverage | Best buy |');
L.push('|---|' + ids.map(() => '---').join('|') + '|---|---|');
for (const sc of out.scenarios) {
  L.push(`| ${sc.name} | ` + sc.results.map((r) => pct(r.patchedByDeadline)).join(' | ') + ` | ${sc.best.most} | **${sc.best.buy}** |`);
}
L.push('', '## Reading it', '');
L.push('- One device (C-08 "Otto", the shock-room C-arm) almost never gets a window the scorer accepts at P(undisturbed) ≥ 0.8. The rules refuse to gamble with it in every option, so it counts as an escalation. In real life, medical physics would swap in the reserve for one night.');
L.push(`- The team rule caps installs at ${P.maxPerNight} per night. That sets the speed limit, not the hardware. With ${P.fleet} C-arms, no option can finish faster than ${Math.ceil((P.fleet - 1) / P.maxPerNight)} nights.`);
L.push('- "Today" is shown for scale only. The two inputs that drive it (`todayLeftOn`, `todayPress`) are guesses. Siemens can replace them with teamplay Fleet data.');
L.push('- Cost figures are rough. The robot uses 2026 dealer list prices for a KettyBot Pro (US$11k–20k); everything else is an assumption. The sources are in `Documentation/architecture-options/00-reference-architecture.md`.', '');
L.push(`Run time: ${(out.ms / 1000).toFixed(1)} s.`);
fs.writeFileSync(path.join(dir, 'RESULTS.md'), L.join('\n') + '\n');
console.log(`wrote results (${(out.ms / 1000).toFixed(1)} s)`);
